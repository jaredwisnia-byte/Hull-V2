"""Writes a sheet-set manifest when the set arrives without one (factory/REFERENCE_SPEC.md v2).

    python3 tools/make_manifest.py NAME DIR --type telephone --cm W D H

DIR holds NAME_painted.png, NAME_depth.png, NAME_parts.png and optionally NAME_section.png.
The five views (front, right, back, left, top, left to right) are found by a gutter cut on
the part map, whose background is pure black. Protocol rule 4: before trusting the set, the
painted and depth sheets must line up with the part map; the manifest records how well
(intersection over union of the object masks) and the build refuses a set that doesn't.
"""
import argparse
import json
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from propkit.facade import _xy_cut  # noqa: E402

VIEWS = ["front", "right", "back", "left", "top"]


def masks(path, thresh):
    a = np.asarray(Image.open(path).convert("RGB")).astype(np.int32)
    border = np.concatenate([a[0], a[-1], a[:, 0], a[:, -1]])
    bg = np.median(border, axis=0)
    return np.abs(a - bg).sum(-1) > thresh


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("dir")
    ap.add_argument("--type", required=True)
    ap.add_argument("--cm", nargs=3, type=float, required=True, metavar=("W", "D", "H"))
    a = ap.parse_args()
    f = lambda k: os.path.join(a.dir, "%s_%s.png" % (a.name, k))
    parts = masks(f("parts"), 60)
    H, W = parts.shape
    leaves = []
    _xy_cut(~parts, 0, 0, W, H, leaves)
    big = sorted([b for b in leaves if (b[2] - b[0]) * (b[3] - b[1]) > 0.004 * W * H], key=lambda b: b[0])
    if len(big) != 5:
        raise SystemExit("expected 5 views on the part map, found %d: %s" % (len(big), big))
    boxes = {v: [int(b[0]), int(b[1]), int(b[2]), int(b[3])] for v, b in zip(VIEWS, big)}
    align = {}
    for k in ("painted", "depth"):
        m = masks(f(k), 40)
        align[k] = round(float((m & parts).sum() / max((m | parts).sum(), 1)), 3)
    man = {"schema_version": "1.0", "asset_id": a.name, "object_type": a.type,
           "dimensions_cm": {"width": a.cm[0], "depth": a.cm[1], "height": a.cm[2], "approximate": True},
           "painted_sheet": {"filename": "%s_painted.png" % a.name, "view_bboxes_px": boxes},
           "depth_map": {"filename": "%s_depth.png" % a.name, "view_bboxes_px": boxes},
           "part_map": {"filename": "%s_parts.png" % a.name, "view_bboxes_px": boxes},
           "alignment_iou_with_part_map": align,
           "notes": ["Generated by tools/make_manifest.py (no manifest came with the set)."]}
    if os.path.exists(f("section")):
        man["section"] = {"filename": "%s_section.png" % a.name}
    json.dump(man, open(os.path.join(a.dir, "%s_manifest.json" % a.name), "w"), indent=1)
    print("MANIFEST", json.dumps({"views": boxes, "alignment": align}))


if __name__ == "__main__":
    main()
